I06_CONFIG = EXPERIMENT_DIR / 'config.yaml'
MARKER = '<!-- GENERATED by experiments/I06_llm_condensation/tools/render_results.py；勿手改 -->'
RESULT_NAME = '6.LLM浓缩-A1-result-癌症为单位.md'
ABLATION_NAME = '6.LLM浓缩-A1-消融表.md'
RESULTS_ROOT = REPO_ROOT / 'experiments' / 'BioClinical ModernBERT' / 'results'
DEFAULT_CONTROLS = {
    'B1': ('bcmbert200', RESULTS_ROOT / 'i05-bcmbert200-20260924d/evidence/formal_eval/runs/test/complete.json'),
    'B2': ('bcmbert8192', RESULTS_ROOT / 'i05-a0-20260924/evidence/formal_eval/runs/test/complete.json'),
}
LABELS = {'T1': '作者特征（Table 1 Proto.）', 'B1': 'B1 NeuML 原文前 200', 'B2': 'B2 NeuML 全文',
          'A1-S': 'A1-S NeuML 结构化', 'A1-Z': 'A1-Z NeuML 摘要', 'A2-S': 'A2-S Qwen 结构化', 'A2-Z': 'A2-Z Qwen 摘要'}
GRID_LABELS = {'none': 'None', 'rna_100': 'RNA masked', 'text_100': 'Text masked', 'both_100': 'Both masked'}
# 研究计划书 4.9：LUAD 的推理路由受已见 test 启发，属探索性。机械门照计五癌，同时给出不计 LUAD 的确认性口径
EXPLORATORY = ('LUAD',)
ATTRIBUTION = ('- 归因：A1 与 B2 编码规格逐项相同（NeuML，max_length 8192、不截断），只差文本来源（浓缩 vs 原文全文），'
               'A1 − B2 是单变量差，为主对照（研究计划书 v3.12 起）；B1 为原文前 200 token，A1 − B1 同时改变文本内容与长度，'
               '只作辅助比较；A2（Qwen）没有同 encoder 的原文对照，只作系统级比较。')


def cancer_label(cancer: str) -> str:
    return f'{cancer}（探索性）' if cancer in EXPLORATORY else cancer


# ----------------------------------------------------------------------------- 读取

def protocol_values(payload: dict, config: dict, protocol: str, *, label: str) -> dict:
    """某一协议的 {(癌种, seed, 场景): C-index}，要求恰好五癌 × 五 seed × 四场景。"""
    values = {}
    for row in payload['rows']:
        if row.get('protocol') != protocol:
            continue
        key = (row['cancer'], int(row['seed']), row['grid'])
        if key in values:
            raise ValueError(f'{label}: {protocol} 行重复 {key}')
        values[key] = float(row['c_index_b'])
    expected = {(c, s, g) for c in config['cancers'] for s in config['seeds'] for g in config['grids']}
    if set(values) != expected:
        raise ValueError(f'{label}: {protocol} 行不完整')
    return values


def load_run(path, i05_config, profile, *, label) -> dict:
    """候选或对照的 test 运行：strategy0（经 I05 load_new 核对档案、状态与协议 ID）与 m0real。"""
    strategy0, meta = i05r.load_new(path, i05_config, profile, label=label)
    payload = json.loads(Path(path).read_text(encoding='utf-8'))
    return {'strategy0': strategy0, 'm0real': protocol_values(payload, i05_config, 'm0real', label=label),
            'meta': meta}


# ----------------------------------------------------------------------------- 判定（纯函数）

def overall(values: dict, cancer: str, config: dict) -> float:
    """论文 Table 1 口径：每个场景五 seed 均值，再四场景等权平均。"""
    return i05r.mean(i05r.mean(values[(cancer, seed, grid)] for seed in config['seeds']) for grid in config['grids'])


def grid_mean(values: dict, cancer: str, grid: str, config: dict) -> float:
    return i05r.mean(values[(cancer, seed, grid)] for seed in config['seeds'])


def check_table1_overall(base: dict, config: dict, i06_config: dict) -> None:
    """基线原始 JSON 全精度算出的 Overall，六位小数必须与论文 Table 1 Proto. 列逐位相同。"""
    for cancer, expected in i06_config['table1_proto']['overall'].items():
        value = overall(base, cancer, config)
        if f'{value:.6f}' != f'{expected:.6f}':
            raise ValueError(f'{cancer}: 基线 Overall {value:.6f} 与 Table 1 的 {expected:.6f} 不一致')


def decide(candidates: dict, base: dict, config: dict, tie_order) -> dict:
    """candidates: {候选名: strategy0 值}。返回逐候选的 Overall、Δ、胜癌（另计不含探索性癌种的 k_confirm）、
    none 口径胜癌，以及胜者与是否达标（机械门照计五癌）。"""
    result = {}
    for name, values in candidates.items():
        per_cancer = {}
        for cancer in config['cancers']:
            ov, base_ov = overall(values, cancer, config), overall(base, cancer, config)
            none, base_none = grid_mean(values, cancer, 'none', config), grid_mean(base, cancer, 'none', config)
            per_cancer[cancer] = {'overall': ov, 'delta': ov - base_ov, 'win': ov > base_ov,
                                  'none_delta': none - base_none, 'none_win': none > base_none}
        result[name] = {'per_cancer': per_cancer,
                        'k': sum(v['win'] for v in per_cancer.values()),
                        'k_confirm': sum(v['win'] for c, v in per_cancer.items() if c not in EXPLORATORY),
                        'k_none': sum(v['none_win'] for v in per_cancer.values()),
                        'mean_delta': i05r.mean(v['delta'] for v in per_cancer.values())}
    order = {name: index for index, name in enumerate(tie_order)}
    winner = sorted(result, key=lambda n: (-result[n]['k'], -result[n]['mean_delta'], order[n]))[0]
    return {'candidates': result, 'winner': winner, 'reached': result[winner]['k'] >= 4}


def retrieval_gain(strategy0: dict, m0real: dict, config: dict) -> dict:
    """检索增益 strategy0 − m0real：逐癌逐场景五 seed 均值、四场景平均，以及四场景平均增益为正的 seed 数。"""
    out = {}
    for cancer in config['cancers']:
        per_grid = {grid: grid_mean(strategy0, cancer, grid, config) - grid_mean(m0real, cancer, grid, config)
                    for grid in config['grids']}
        per_seed = [i05r.mean(strategy0[(cancer, s, g)] - m0real[(cancer, s, g)] for g in config['grids'])
                    for s in config['seeds']]
        out[cancer] = {'per_grid': per_grid, 'average': i05r.mean(per_grid.values()),
                       'k_positive_seeds': sum(v > 0 for v in per_seed)}
    return out


# ----------------------------------------------------------------------------- 渲染

def _bold_max(cells: dict) -> dict:
    """一行里未舍入最高值加粗，并列都加粗。"""
    top = max(cells.values())
    return {k: (f'**{i05r.fmt(v)}**' if v == top else i05r.fmt(v)) for k, v in cells.items()}


def render_result(config, i06_config, base, runs, decision, retrieval, metas) -> str:
    cancers = i06_config['display_cancer_order']
    cols = ['T1', 'B1', 'B2', *i06_config['candidate_tie_order']]
    values = {'T1': base, **{k: runs[k]['strategy0'] for k in cols[1:]}}
    winner = decision['winner']
    n_confirm = sum(c not in EXPLORATORY for c in config['cancers'])
    lines = [MARKER, '', '# 6.LLM浓缩-A1：癌症为单位', '']
    lines.append('> 数据来源（sha256）：' + '；'.join(f'{k} `{metas[k]["sha256"]}`' for k in sorted(metas)) + '。')
    lines += ['', '## 口径', '',
              '- 数值为 test 上 B 口径 C-index，全部为开检索（Proto. = strategy0）。每癌先对每个场景取五 seed 均值，'
              '再对 None / RNA masked / Text masked / Both masked 等权平均得 **Overall**（与论文 Table 1 相同）。',
              '- 判定：候选的 Overall 与 Table 1 Proto. 列的 Overall 逐癌比较，未舍入严格 > 记胜、相等不算胜；'
              '四个候选中任一候选胜 ≥4/5 即达标。胜者 = 胜癌数最多者，相同比五癌平均 Overall Δ，仍相同按 '
              + '、'.join(i06_config['candidate_tie_order']) + ' 的顺序。',
              ATTRIBUTION,
              f'- {"、".join(EXPLORATORY)} 的推理路由受已见 test 启发（研究计划书 4.9），其各列数字属探索性：主判定按预先定义'
              f'照计五癌（机械门），同时给出不计 {"、".join(EXPLORATORY)} 的确认性口径（k/{n_confirm}）。',
              f'- 零效应下单个候选至少 4/5 严格胜出的偶然概率约 {i05r.chance_at_least(4):.1%}；四个候选全部报告。', '']
    lines += ['## 五癌 Overall 汇总（主判定）', '']
    rows = []
    for cancer in cancers:
        cells = _bold_max({c: overall(values[c], cancer, config) for c in cols})
        rows.append([cancer_label(cancer), *[cells[c] for c in cols]])
    lines += i05r.table(['癌种', *[LABELS[c] for c in cols]], rows) + ['']
    rows = []
    for name in i06_config['candidate_tie_order']:
        item = decision['candidates'][name]
        wins = [cancer_label(c) for c in cancers if item['per_cancer'][c]['win']]
        rows.append([LABELS[name], f"{item['k']}/5", f"{item['k_confirm']}/{n_confirm}", i05r.fmt_delta(item['mean_delta']),
                     '、'.join(wins) or '—', f"{item['k_none']}/5", '是' if name == winner else ''])
    lines += i05r.table(['候选', 'Overall 严格胜', f'不计 {"、".join(EXPLORATORY)}（确认性）', '五癌平均 Overall Δ',
                         '胜的癌种', 'None 行严格胜（参考）', '胜者'], rows)
    lines += ['', f"**胜者：{LABELS[winner]}，Overall 严格胜 {decision['candidates'][winner]['k']}/5"
                  f"（不计探索性的 {'、'.join(EXPLORATORY)}：{decision['candidates'][winner]['k_confirm']}/{n_confirm}），"
                  f"{'达标' if decision['reached'] else '未达标'}（目标 ≥4/5）。**", '']
    neuml = [n for n in i06_config['candidate_tie_order'] if i06_config['candidates'][n]['encoder'] == 'neuml']
    lines += ['## 同 encoder 归因（NeuML：A1 − B2 为主对照，A1 − B1 为辅助）', '',
              '逐癌 Overall 差；A1 − B2 只差文本来源（浓缩 vs 原文全文），A1 − B1 同时改变文本内容与长度。'
              '只报为正的癌种数，不做显著性检验。', '']
    rows = []
    for control, tag in (('B2', '主对照'), ('B1', '辅助')):
        for name in neuml:
            deltas = {c: overall(values[name], c, config) - overall(values[control], c, config) for c in cancers}
            rows.append([f'{name} − {control}（{tag}）', *[i05r.fmt_delta(deltas[c]) for c in cancers],
                         f'{sum(d > 0 for d in deltas.values())}/5'])
    lines += i05r.table(['比较', *[cancer_label(c) for c in cancers], '为正的癌种'], rows) + ['']
    lines += ['## 按癌种展开', '']
    for cancer in cancers:
        lines += [f'### {cancer_label(cancer)}', '']
        if cancer in EXPLORATORY:
            lines += ['推理路由受已见 test 启发（研究计划书 4.9），本节数字属探索性。', '']
        rows = []
        for seed in config['seeds']:
            for grid in config['grids']:
                cells = {c: values[c][(cancer, seed, grid)] for c in cols}
                shown = _bold_max(cells)
                delta = cells[winner] - cells['T1']
                better = LABELS[winner] if delta > 0 else ('并列' if delta == 0 else LABELS['T1'])
                rows.append([str(seed), GRID_LABELS[grid], *[shown[c] for c in cols], better, i05r.fmt_delta(delta)])
        for grid in config['grids']:
            cells = {c: grid_mean(values[c], cancer, grid, config) for c in cols}
            shown = _bold_max(cells)
            rows.append(['五 seed 均值', GRID_LABELS[grid], *[shown[c] for c in cols], '',
                         i05r.fmt_delta(cells[winner] - cells['T1'])])
        cells = {c: overall(values[c], cancer, config) for c in cols}
        shown = _bold_max(cells)
        rows.append(['**Overall**', '四场景平均', *[shown[c] for c in cols], '',
                     i05r.fmt_delta(cells[winner] - cells['T1'])])
        lines += i05r.table(['Seed', '场景', *[LABELS[c] for c in cols], '较优（胜者 vs Table 1）', f'Δ（{winner} − Table 1）'],
                            rows) + ['']
    lines += [f'## 患者检索效果（胜者 {LABELS[winner]}：strategy0 − m0real）', '']
    rows = []
    for cancer in cancers:
        item = retrieval[cancer]
        rows.append([cancer_label(cancer), *[i05r.fmt_delta(item['per_grid'][g]) for g in config['grids']],
                     i05r.fmt_delta(item['average']), f"{item['k_positive_seeds']}/5"])
    lines += i05r.table(['癌种', *[GRID_LABELS[g] for g in config['grids']], '四场景平均', '四场景平均增益为正的 seed'], rows)
    top = max(retrieval[c]['average'] for c in cancers)
    best = [cancer_label(c) for c in cancers if retrieval[c]['average'] == top]
    lines += ['', f"检索效果最好（四场景平均增益最大）的癌种：{'、'.join(best)}（{i05r.fmt_delta(top)}）。"
                  'None 下完整患者不走检索，只有天然缺失者走检索，会拉低平均。', '']
    lines += ['## 癌种结论', '']
    item = decision['candidates'][winner]
    same_encoder = i06_config['candidates'][winner]['encoder'] == 'neuml'
    for cancer in cancers:
        pc = item['per_cancer'][cancer]
        d1 = i05r.fmt_delta(pc['overall'] - overall(values['B1'], cancer, config))
        d2 = i05r.fmt_delta(pc['overall'] - overall(values['B2'], cancer, config))
        refs = (f'对 B2 {d2}（主对照）；对 B1 {d1}（辅助）' if same_encoder
                else f'对 B2 {d2}、对 B1 {d1}（不同 encoder，只作系统级参考）')
        lines.append(f"- {cancer_label(cancer)}：胜者 Overall {i05r.fmt(pc['overall'])}，对 Table 1 {i05r.fmt_delta(pc['delta'])}"
                     f"（{'胜' if pc['win'] else '负'}）；{refs}。")
    return '\n'.join(lines) + '\n'


def render_ablation(config, i06_config, base, runs) -> str:
    """Text 表征消融（版式照论文 Table 1，只列 Proto.）：NeuML 一张、Qwen 一张。"""
    cancers = i06_config['display_cancer_order']
    lines = [MARKER, '', '# Text 表征消融（只列 Proto. = strategy0）', '',
             '行 = 四场景 + Overall；每癌每行未舍入最高值加粗、并列都加粗。归因看 NeuML 表中 A1 − B2（同 encoder、同 8192 '
             '编码规格，只换文本来源；主对照）；A1 − B1 同时改变文本内容与长度，只作辅助比较。Qwen 表没有同 encoder 原文对照，'
             f'只作系统级比较。{"、".join(EXPLORATORY)} 的推理路由受已见 test 启发，属探索性。', '']
    for title, cols in (('NeuML（BioClinical ModernBERT 嵌入版）', ['T1', 'B1', 'B2', 'A1-S', 'A1-Z']),
                        ('Qwen3-Embedding-0.6B', ['T1', 'A2-S', 'A2-Z'])):
        values = {'T1': base, **{k: runs[k]['strategy0'] for k in cols if k != 'T1'}}
        header = ['场景'] + [f'{cancer_label(cancer)} · {LABELS[c]}' for cancer in cancers for c in cols]
        rows = []
        for grid in [*config['grids'][1:], config['grids'][0]]:
            row = [GRID_LABELS[grid]]
            for cancer in cancers:
                shown = _bold_max({c: grid_mean(values[c], cancer, grid, config) for c in cols})
                row += [shown[c] for c in cols]
            rows.append(row)
        row = ['Overall']
        for cancer in cancers:
            shown = _bold_max({c: overall(values[c], cancer, config) for c in cols})
            row += [shown[c] for c in cols]
        rows.append(row)
        lines += [f'## {title}', ''] + i05r.table(header, rows) + ['']
    return '\n'.join(lines) + '\n'


def render_all(*, baseline, controls, candidates, i06_config=None) -> dict:
    i06_config = i06_config or json.loads(I06_CONFIG.read_text(encoding='utf-8'))
    config = i05r.load_config()
    base, base_meta = i05r.load_baseline(baseline, config)
    check_table1_overall(base, config, i06_config)
    runs, metas = {}, {'T1': base_meta}
    for name, (profile, path) in controls.items():
        runs[name] = load_run(path, config, profile, label=name)
    for name, spec in i06_config['candidates'].items():
        runs[name] = load_run(candidates[name], config, spec['profile'], label=name)
    for name, run in runs.items():
        metas[name] = run['meta']
    decision = decide({n: runs[n]['strategy0'] for n in i06_config['candidate_tie_order']}, base, config,
                      i06_config['candidate_tie_order'])
    winner = decision['winner']
    retrieval = retrieval_gain(runs[winner]['strategy0'], runs[winner]['m0real'], config)
    return {RESULT_NAME: render_result(config, i06_config, base, runs, decision, retrieval, metas),
            ABLATION_NAME: render_ablation(config, i06_config, base, runs), 'decision': decision}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--candidate', action='append', required=True, metavar='名称=complete.json',
                        help='四个候选各一次：A1-S / A1-Z / A2-S / A2-Z')
    parser.add_argument('--baseline', type=Path, default=None, help='默认取 I05 config 的 legacy.test_complete')
    parser.add_argument('--out-dir', type=Path, required=True)
    args = parser.parse_args(argv)
    candidates = dict(item.split('=', 1) for item in args.candidate)
    i06_config = json.loads(I06_CONFIG.read_text(encoding='utf-8'))
    if set(candidates) != set(i06_config['candidates']):
        parser.error(f'必须恰好给出四个候选: {sorted(i06_config["candidates"])}')
    baseline = args.baseline or REPO_ROOT / i05r.load_config()['legacy']['test_complete']
    rendered = render_all(baseline=baseline, controls=DEFAULT_CONTROLS, candidates=candidates, i06_config=i06_config)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name in (RESULT_NAME, ABLATION_NAME):
        with (args.out_dir / name).open('x', encoding='utf-8') as handle:
            handle.write(rendered[name])
    decision = rendered['decision']
    print(json.dumps({'winner': decision['winner'], 'reached': decision['reached'],
                      'k': {n: v['k'] for n, v in decision['candidates'].items()}}, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
