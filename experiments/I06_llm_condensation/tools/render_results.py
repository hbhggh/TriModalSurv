"""I06 结果渲染（研究计划书 3.1、4.9、4.10）：结果文档 R（癌症为单位）与 Text 表征消融表 X。

判定口径照论文 Table 1：每癌先对每个场景取五 seed 均值，再对 none / rna_100 / text_100 / both_100 等权平均得 Overall；
四个候选（A1-S、A1-Z、A2-S、A2-Z）的 Overall 与 Table 1 Proto. 列的 Overall 逐癌比较，全精度严格 > 记胜。
任一候选胜 ≥4/5 即达标；胜者 = 胜癌数最多者，相同比五癌平均 Overall Δ，仍相同按 config.candidate_tie_order。
患者检索效果（胜者）：strategy0 − m0real，先五 seed 均值、再四场景平均，最大者为检索效果最好。
输入只认原始 JSON（基线 = Table 1 所用的 4.progress test 运行；B1 / B2 = I05 两次 test 运行；候选 = I05 评测器
对四个 I06 档案的 test 运行）。所有比较用未舍入值，展示六位；同样输入两次渲染字节一致；输出文件已存在即失败。
"""
