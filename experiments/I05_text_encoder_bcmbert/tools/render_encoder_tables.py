#!/usr/bin/env python3
"""I05 结果渲染：两份四场景结果表、4×5 Encoder 表，以及 none 下的 Q 判定。

输入只认原始 JSON：基线取 4.progress ``runs/test/complete.json`` 的 strategy0 行（即论文 Table 1
的 Proto.†），新臂取 I05 ``evaluate.py --stage test`` 产出的 ``complete.json``（可缺省，缺省时新臂写"未实验"）。
所有比较、标红与 Δ 都用未舍入值；展示六位，Δ 先减后舍入；平局两臂同时标红、不算胜（坑 V23：
进结论的数字只来自本脚本）。输出确定：同样输入连续两次渲染字节一致。
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from itertools import combinations
from pathlib import Path

TOOLS_DIR = Path(__file__).resolve().parent
EXPERIMENT_DIR = TOOLS_DIR.parent
REPO_ROOT = EXPERIMENT_DIR.parents[1]
DEFAULT_CONFIG = EXPERIMENT_DIR / 'config.yaml'
MARKER = '<!-- GENERATED by experiments/I05_text_encoder_bcmbert/tools/render_encoder_tables.py；勿手改 -->'
NEW_LABEL = '我们提出来的 Encoder'
BASE_LABEL = '现有系统 Proto.†'
NOT_RUN = '未实验'
FILENAMES = ('seed单位-实验结果.md', '癌症为单位.md', 'encoder-table.md')


def sha256_file(path) -> str:
    digest = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


REQUIRED_SEEDS = (123, 132, 213, 231, 321)


def load_config(path=DEFAULT_CONFIG) -> dict:
    config = json.loads(Path(path).read_text(encoding='utf-8'))
    if tuple(config['seeds']) != REQUIRED_SEEDS:
        raise ValueError('I05 的实验种子必须是 123、132、213、231、321（用户锁定）')
    return config


def strategy0_values(payload: dict, config: dict, *, label: str) -> dict:
    """抽取 strategy0 行为 {(癌种, seed, 场景): C-index}，要求恰好五癌×五 seed×四场景、无重复。"""
    cancers, seeds, grids = config['cancers'], config['seeds'], config['grids']
    values = {}
    for row in payload['rows']:
        if row.get('protocol') != 'strategy0':
            continue
        key = (row['cancer'], int(row['seed']), row['grid'])
        if key in values:
            raise ValueError(f'{label}: strategy0 行重复 {key}')
        value = row['c_index_b']
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) \
                or not 0.0 <= float(value) <= 1.0:
            raise ValueError(f'{label}: {key} 的 C-index 非法')
        values[key] = float(value)
    expected = {(cancer, seed, grid) for cancer in cancers for seed in seeds for grid in grids}
    if set(values) != expected:
        raise ValueError(f'{label}: strategy0 行不完整，缺 {len(expected - set(values))}、多 {len(set(values) - expected)}')
    return values


def load_baseline(path, config) -> tuple:
    path = Path(path)
    payload = json.loads(path.read_text(encoding='utf-8'))
    if payload.get('run_fingerprint') != config['legacy']['test_run_fingerprint']:
        raise ValueError('基线不是 Table 1 所用的 4.progress test 运行')
    values = strategy0_values(payload, config, label='基线')
    q_grid = config['q_grid']
    for cancer, expected in ((c, config['table1_none_proto'][c]) for c in config['cancers']):
        mean = sum(values[(cancer, seed, q_grid)] for seed in config['seeds']) / len(config['seeds'])
        if f'{mean:.6f}' != f'{expected:.6f}':
            raise ValueError(f'{cancer}: 基线 none 五 seed 均值 {mean:.6f} 与 Table 1 的 {expected:.6f} 不一致')
    return values, {'path': path.as_posix(), 'sha256': sha256_file(path), 'run_fingerprint': payload['run_fingerprint']}


def load_new(path, config) -> tuple:
    path = Path(path)
    payload = json.loads(path.read_text(encoding='utf-8'))
    if payload.get('stage') != 'test' or payload.get('status') != 'COMPLETED' or payload.get('profile') != 'bcmbert200':
        raise ValueError('新臂必须是 bcmbert200 档案、已完成的 test 运行')
    if payload.get('protocol_id') != config['protocol_ids']['bcmbert200']:
        raise ValueError('新臂协议 ID 与 config 不一致')
    values = strategy0_values(payload, config, label='新臂')
    return values, {'path': path.as_posix(), 'sha256': sha256_file(path), 'run_fingerprint': payload['run_fingerprint']}


def fmt(value: float) -> str:
    return f'{value:.6f}'


def fmt_delta(value: float) -> str:
    return f'{value:+.6f}'


def red(text: str) -> str:
    return f'<span style="color:#c62828"><strong>{text}</strong></span>'


def compare_cells(new, base) -> list:
    """返回 [新臂, 现有系统, 较优, Δ] 四格；未舍入比较，平局两边都标红。"""
    if new is None:
        return [NOT_RUN, fmt(base), '—', NOT_RUN]
    if new > base:
        return [red(fmt(new)), fmt(base), red(NEW_LABEL), fmt_delta(new - base)]
    if base > new:
        return [fmt(new), red(fmt(base)), red(BASE_LABEL), fmt_delta(new - base)]
    return [red(fmt(new)), red(fmt(base)), red('并列'), fmt_delta(new - base)]


def table(header: list, rows: list) -> list:
    lines = ['| ' + ' | '.join(header) + ' |', '| ' + ' | '.join('---' for _ in header) + ' |']
    for row in rows:
        if len(row) != len(header):
            raise ValueError('表格行列数与表头不一致')
        lines.append('| ' + ' | '.join(row) + ' |')
    return lines


def mean(values) -> float:
    values = list(values)
    return sum(values) / len(values)


def chance_at_least(k: int, n: int = 5) -> float:
    """零效应、各癌胜负独立且对称时，至少 k 癌严格胜出的概率。"""
    return sum(len(list(combinations(range(n), j))) for j in range(k, n + 1)) / 2 ** n


def best(items: dict) -> str:
    """取最大值对应的键；并列时全部列出。"""
    top = max(items.values())
    return '、'.join(f'`{key}`' for key, value in items.items() if value == top)


def disclosure(config, base_meta, new_meta) -> list:
    encoder = config['text_encoder']
    lines = ['## 口径与解释边界', '']
    lines.append(f"- **现有系统**：`{config['legacy']['test_complete']}` 的 strategy0 行，即论文 Table 1 的 "
                 f"Proto.†（test 指纹 `{base_meta['run_fingerprint']}`）。非 LUAD 为 2.progress 冻结组合，LUAD 为 "
                 'S0-force 强制路由；该路由受已见 test 启发，存在 test 泄漏，属探索性结果。')
    if new_meta is None:
        lines.append(f'- **{NEW_LABEL}**：新 encoder 成绩尚未产生，本文件是模板，新臂列统一写"未实验"。')
    else:
        lines.append(f"- **{NEW_LABEL}**：I05 `bcmbert200` 档案的 test 运行（指纹 `{new_meta['run_fingerprint']}`）。")
    lines.append(f"- 本实验只换 Text：`{encoder['model_id']}`@`{encoder['revision'][:8]}`，冻结，截断或补齐到 "
                 f"{encoder['max_length']} token，有效 token 均值广播到 200 行（方案 C）；WSI（UNI2-h）与 RNA（自制 BulkRNABert）不变。25 个 ckpt "
                 '在现行代码上按原配方重训；原型检索参数（λ=1、α=1、w=0.5）与 LUAD 路由冻结不变。')
    lines.append('- `none` 保留天然缺失，不是完整数据。只有 `none` 进入 Q 判定：Δ_c > 0 的癌种数达到 4/5 为达标，'
                 '平局不算胜；`rna_100`、`text_100`、`both_100` 只作附录。')
    lines.append('- 比较与标红按未舍入值；展示六位；Δ 先减后舍入；平局两臂同时标红。')
    lines.append(f'- 解释边界：Δ 同时包含 encoder 效应与重训方差；只换了 Text，结论不支持"每个模态的 encoder 都更好"；'
                 f'none 下完整患者不走检索，Proto.† 在这些患者上等于基础模型；零效应下至少 4/5 严格胜出的偶然概率约 '
                 f'{chance_at_least(4) * 100:.1f}%。')
    lines.append('')
    return lines


def _header(title, base_meta, new_meta) -> list:
    source = f"基线 sha256 `{base_meta['sha256']}`"
    if new_meta is not None:
        source += f"；新臂 sha256 `{new_meta['sha256']}`"
    return [MARKER, '', f'# {title}', '', f'> 数据来源：{source}。', '']


def _order(config):
    return config['display_cancer_order'], config['seeds'], config['grids'], config['q_grid']


def render_seed(config, base, new, base_meta, new_meta) -> str:
    cancers, seeds, grids, q_grid = _order(config)
    lines = _header('seed单位-实验结果', base_meta, new_meta) + disclosure(config, base_meta, new_meta)
    lines += ['## 按 seed 展开', '']
    for seed in seeds:
        rows = [[cancer, grid, *compare_cells(None if new is None else new[(cancer, seed, grid)],
                                              base[(cancer, seed, grid)])]
                for cancer in cancers for grid in grids]
        lines += [f'### Seed {seed}', '', *table(['癌种', '场景', NEW_LABEL, BASE_LABEL, '较优', 'Δ（新−现有）'], rows), '']
    lines += ['## seed结论', '']
    if new is None:
        lines.append(f'{NOT_RUN}：新 encoder 成绩尚未产生，无法判定效果最好的 seed。')
    else:
        none_abs = {seed: mean(new[(c, seed, q_grid)] for c in cancers) for seed in seeds}
        none_delta = {seed: mean(new[(c, seed, q_grid)] - base[(c, seed, q_grid)] for c in cancers) for seed in seeds}
        all_abs = {seed: mean(new[(c, seed, g)] for c in cancers for g in grids) for seed in seeds}
        all_delta = {seed: mean(new[(c, seed, g)] - base[(c, seed, g)] for c in cancers for g in grids) for seed in seeds}
        lines.append(f'none（Q 口径）：{NEW_LABEL}五癌平均 C-index 最高的 seed：{best(none_abs)}。')
        lines.append(f'none（Q 口径）：相对现有系统五癌平均 Δ 最大的 seed：{best(none_delta)}。二者不混称，且不替代五 seed 结论。')
        lines.append(f'四场景（附录，不进 Q）：平均 C-index 最高的 seed：{best(all_abs)}；平均 Δ 最大的 seed：{best(all_delta)}。')
    lines.append('')
    return '\n'.join(lines)


def q_judgement(config, base, new) -> dict:
    cancers, seeds, _, q_grid = _order(config)
    result = {}
    for cancer in cancers:
        base_mean = mean(base[(cancer, seed, q_grid)] for seed in seeds)
        if new is None:
            result[cancer] = {'base': base_mean, 'new': None, 'delta': None, 'verdict': NOT_RUN}
            continue
        new_mean = mean(new[(cancer, seed, q_grid)] for seed in seeds)
        delta = new_mean - base_mean
        verdict = '胜' if delta > 0 else '负' if delta < 0 else '平'
        result[cancer] = {'base': base_mean, 'new': new_mean, 'delta': delta, 'verdict': verdict}
    return result


def q_line(config, judgement) -> str:
    if any(item['new'] is None for item in judgement.values()):
        return f'严格胜率（none，Q 判定）：{NOT_RUN}。'
    wins = [cancer for cancer, item in judgement.items() if item['verdict'] == '胜']
    others = [cancer for cancer in judgement if cancer not in wins]
    status = '达标' if len(wins) >= 4 else '未达标'
    return (f"严格胜率（none，Q 判定）：**{len(wins)}/{len(judgement)}**（{status}）；未胜癌种："
            f"{'、'.join(others) if others else '无'}。")


def render_cancer(config, base, new, base_meta, new_meta) -> str:
    cancers, seeds, grids, q_grid = _order(config)
    judgement = q_judgement(config, base, new)
    lines = _header('癌症为单位', base_meta, new_meta) + disclosure(config, base_meta, new_meta)
    lines += ['## 五癌 none 汇总（Q 判定）', '']
    rows = []
    for cancer in cancers:
        item = judgement[cancer]
        if item['new'] is None:
            rows.append([cancer, NOT_RUN, fmt(item['base']), NOT_RUN, NOT_RUN])
        else:
            new_text, base_text, _, delta_text = compare_cells(item['new'], item['base'])
            rows.append([cancer, new_text, base_text, delta_text, item['verdict']])
    lines += table(['癌种', f'{NEW_LABEL}（五 seed 均值）', f'{BASE_LABEL}（五 seed 均值）', 'Δ_c', '判定'], rows)
    lines += ['', q_line(config, judgement), '', '## 按癌种展开', '']
    for cancer in cancers:
        rows = [[str(seed), grid, *compare_cells(None if new is None else new[(cancer, seed, grid)],
                                                 base[(cancer, seed, grid)])]
                for seed in seeds for grid in grids]
        lines += [f'### {cancer}', '', *table(['Seed', '场景', NEW_LABEL, BASE_LABEL, '较优', 'Δ（新−现有）'], rows), '']
    lines += ['## 癌种结论', '']
    if new is None:
        lines.append(f'{NOT_RUN}：新 encoder 成绩尚未产生，无法判定效果最好的癌种。')
    else:
        none_abs = {cancer: judgement[cancer]['new'] for cancer in cancers}
        none_delta = {cancer: judgement[cancer]['delta'] for cancer in cancers}
        pairs_abs = {f'{c}/{g}': mean(new[(c, s, g)] for s in seeds) for c in cancers for g in grids}
        pairs_delta = {f'{c}/{g}': mean(new[(c, s, g)] - base[(c, s, g)] for s in seeds) for c in cancers for g in grids}
        lines.append(f'none（Q 口径）：{NEW_LABEL}五 seed 平均 C-index 最高的癌种：{best(none_abs)}。')
        lines.append(f'none（Q 口径）：相对现有系统 Δ 最大的癌种：{best(none_delta)}。二者不混称。')
        lines.append(f'四场景（附录，不进 Q）：平均 C-index 最高的癌种×场景：{best(pairs_abs)}；'
                     f'平均 Δ 最大的癌种×场景：{best(pairs_delta)}。')
        lines.append(q_line(config, judgement))
    lines.append('')
    return '\n'.join(lines)


def render_encoder_table(config, base, new, base_meta, new_meta) -> str:
    cancers = config['display_cancer_order']
    judgement = q_judgement(config, base, new)
    lines = _header('4×5 Encoder 对比表（none）', base_meta, new_meta)
    lines += ['场景为 `none`（保留天然缺失）；数值为五 seed 平均 B 口径 C-index。', '']
    ours = [NOT_RUN if judgement[c]['new'] is None else fmt(judgement[c]['new']) for c in cancers]
    lines += table(['Encoder', *cancers], [
        ['MLP', *(['未实验（占位）'] * len(cancers))],
        ['原论文的 Encoder', *([NOT_RUN] * len(cancers))],
        ['其他方法的 Encoder', *(['未实验（算法待定）'] * len(cancers))],
        [NEW_LABEL, *ours],
    ])
    lines += ['', '表外独立参考：', '']
    deltas = [NOT_RUN if judgement[c]['delta'] is None else fmt_delta(judgement[c]['delta']) for c in cancers]
    lines += table(['对照', *cancers], [
        ['现有系统 None / Proto.†（Table 1）', *[fmt(judgement[c]['base']) for c in cancers]],
        [f'Δ_c（{NEW_LABEL} − 现有系统）', *deltas],
        ['判定', *[judgement[c]['verdict'] for c in cancers]],
    ])
    lines += ['', q_line(config, judgement), '', '注：', '']
    lines.append(f'1. 「{NEW_LABEL}」= UNI2-h（WSI，不变）+ BioClinical ModernBERT 嵌入版（Text，本实验唯一改动）'
                 '+ 自制 BulkRNABert（RNA，不变）。')
    lines.append('2. 「其他方法的 Encoder」只是占位行，具体算法尚未确定。')
    lines.append('3. 「MLP」行的层级、输入与训练方式尚未定义，同样只占位。')
    lines.append('4. 现有系统的 Text 为作者公开嵌入，编码器身份未核；WSI 用 UNI2-h，而原论文为 ViT/Marugoto。'
                 '因此现有系统不塞进「原论文的 Encoder」行，放在表外作独立参考。')
    lines.append('')
    return '\n'.join(lines)


def render_all(config, base, new, base_meta, new_meta) -> dict:
    documents = {
        FILENAMES[0]: render_seed(config, base, new, base_meta, new_meta),
        FILENAMES[1]: render_cancer(config, base, new, base_meta, new_meta),
        FILENAMES[2]: render_encoder_table(config, base, new, base_meta, new_meta),
    }
    for name, text in documents.items():
        check_tables(text, name)
    return documents


def check_tables(text: str, name: str = '') -> None:
    """每张表的分隔行与数据行列数必须等于表头列数（I01 模板曾出现损坏的分隔行）。"""
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        if lines[index].startswith('| ') and index + 1 < len(lines) and lines[index + 1].startswith('| ---'):
            width = lines[index].count(' | ') + 1
            if lines[index + 1].count(' | ') + 1 != width:
                raise ValueError(f'{name}: 第 {index + 2} 行分隔行列数不符')
            cursor = index + 2
            while cursor < len(lines) and lines[cursor].startswith('| '):
                if lines[cursor].count(' | ') + 1 != width:
                    raise ValueError(f'{name}: 第 {cursor + 1} 行列数不符')
                cursor += 1
            index = cursor
        else:
            index += 1


def write_documents(documents: dict, out_dir) -> list:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in documents.items():
        path = out_dir / name
        if path.exists() and not path.read_text(encoding='utf-8').startswith(MARKER):
            raise FileExistsError(f'拒绝覆盖非本脚本生成的文件: {path}')
        temporary = path.with_name('.' + path.name + '.tmp')
        temporary.write_text(text, encoding='utf-8')
        temporary.replace(path)
        written.append(path)
    return written


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--config', type=Path, default=DEFAULT_CONFIG)
    parser.add_argument('--baseline', type=Path, help='缺省为 config.legacy.test_complete')
    parser.add_argument('--new', type=Path, help='I05 test 阶段的 complete.json；缺省时新臂写"未实验"')
    parser.add_argument('--out-dir', type=Path, required=True)
    args = parser.parse_args(argv)
    config = load_config(args.config)
    baseline_path = args.baseline or REPO_ROOT / config['legacy']['test_complete']
    base, base_meta = load_baseline(baseline_path, config)
    base_meta['path'] = config['legacy']['test_complete'] if args.baseline is None else base_meta['path']
    new, new_meta = (None, None) if args.new is None else load_new(args.new, config)
    written = write_documents(render_all(config, base, new, base_meta, new_meta), args.out_dir)
    print(json.dumps({'written': [path.name for path in written], 'new_arm': new is not None}, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
